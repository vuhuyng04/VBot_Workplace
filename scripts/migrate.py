"""Apply app/migrations/*.sql through the RDS Data API with the master secret, then set the
password of the RLS-restricted role vbot_app from its Secrets Manager secret.
Wakes an auto-paused Aurora Serverless v2 cluster (retries while it resumes).

Usage: .venv/Scripts/python scripts/migrate.py
"""
import json
import pathlib
import subprocess
import time

import boto3

ROOT = pathlib.Path(__file__).resolve().parents[1]
TF = ROOT / "infra" / "envs" / "mvp"


def tf_outputs():
    out = subprocess.run(["terraform", f"-chdir={TF}", "output", "-json"], capture_output=True, text=True, check=True).stdout
    return {k: v["value"] for k, v in json.loads(out).items()}


def main():
    o = tf_outputs()
    s = boto3.Session(region_name="us-east-1")  # credentials: AWS_PROFILE locally, OIDC in CI
    rds, sm = s.client("rds-data"), s.client("secretsmanager")
    cluster, master = o["data"]["db_cluster_arn"], o["data"]["db_secret_arn"]

    def run(sql, **params):
        p = [{"name": k, "value": {"stringValue": v}} for k, v in params.items()]
        for _attempt in range(30):
            try:
                return rds.execute_statement(resourceArn=cluster, secretArn=master, database="vbot", sql=sql, parameters=p)
            except rds.exceptions.DatabaseResumingException:
                print("  Aurora is resuming from auto-pause, waiting…")
                time.sleep(10)
            except Exception as e:
                if "resum" in str(e).lower() or "Communications link failure" in str(e):
                    time.sleep(10)
                    continue
                raise
        raise SystemExit("database did not resume")

    for f in sorted((ROOT / "app" / "migrations").glob("*.sql")):
        stmts = [x.strip() for x in f.read_text(encoding="utf-8").split("--;;") if x.strip()]
        print(f"{f.name}: {len(stmts)} statements")
        for st in stmts:
            try:
                run(st)
            except Exception as e:
                raise SystemExit(f"FAILED: {st[:200]} -> {e}") from e
    pw = json.loads(sm.get_secret_value(SecretId=o["app"]["db_app_secret"])["SecretString"])["password"]
    run(f"ALTER ROLE vbot_app WITH LOGIN PASSWORD '{pw}'")  # alphanumeric, generated by Terraform
    print("vbot_app password set; tables:",
          [r[0]["stringValue"] for r in run("SELECT tablename FROM pg_tables WHERE schemaname = 'public' ORDER BY 1")["records"]])


if __name__ == "__main__":
    main()
